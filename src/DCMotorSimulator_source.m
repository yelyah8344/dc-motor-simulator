        % Button pushed function: CompareMethodsButton
        function CompareMethodsButtonPushed(app, event)
            if app.IsRunning
                return;
            end
            app.IsRunning = true;
            cleanupObj = onCleanup(@() app.setRunningFalse());
            app.CompareStatusLabel.Text = 'Status: Simulating...';
            app.CompareStatusLabel.FontColor = 'red';
            drawnow;

            try
                if app.SimulationDurationEditField.Value <= 0 || app.TimeStepEditField.Value <= 0
                    uialert(app.UIFigure, 'Simulation Duration and Time Step must be greater than zero.', 'Invalid Input');
                    app.CompareStatusLabel.Text = 'Status: Ready';
                    app.CompareStatusLabel.FontColor = 'green';
                    return;
                end

                p = app.getSimParams();
                if p.Ra <= 0 || p.La <= 0 || p.Kt < 0 || p.Ke < 0 || p.J <= 0 || p.B < 0 || p.ILimit <= 0
                    uialert(app.UIFigure, 'Check motor parameters. R, L, J and current limit must be positive; friction/constants cannot be negative.', 'Invalid Motor Parameters');
                    app.CompareStatusLabel.Text = 'Status: Ready';
                    app.CompareStatusLabel.FontColor = 'green';
                    return;
                end

                [Va_func, success] = app.getVoltageFunction(p.V_mag, p.t_end);
                if ~success
                    app.CompareStatusLabel.Text = 'Status: Ready';
                    app.CompareStatusLabel.FontColor = 'green';
                    return;
                end
                TL_func = app.getTorqueFunction(p);

                % Same time grid and same model as the main solver.
                t = DCMotorSimulator.makeTimeVector(p.t_end, p.h);
                x_euler = DCMotorSimulator.runEulerFixedStep(p, Va_func, TL_func, t);
                x_rk4   = DCMotorSimulator.runRK4FixedStep(p, Va_func, TL_func, t);

                w_euler = x_euler(2,:);
                w_rk4   = x_rk4(2,:);

                unstable = any(~isfinite(x_euler(:))) || any(~isfinite(x_rk4(:))) || max(abs(w_euler), [], 'omitnan') > 1e6 || max(abs(w_rk4),   [], 'omitnan') > 1e6;

                if unstable
                    uialert(app.UIFigure, 'Numerical instability detected. Reduce the time step.', 'Simulation Failed', 'Icon', 'error');
                    app.CompareStatusLabel.Text = 'Status: Ready';
                    app.CompareStatusLabel.FontColor = 'green';
                    return;
                end

                cla(app.MethodCompareAxes);
                plot(app.MethodCompareAxes, t, w_euler, 'r--', 'LineWidth', 1.5, 'DisplayName', 'Euler Method');
                hold(app.MethodCompareAxes, 'on');
                plot(app.MethodCompareAxes, t, w_rk4, 'b-', 'LineWidth', 1.5, 'DisplayName', 'RK4 Method');
                hold(app.MethodCompareAxes, 'off');

                grid(app.MethodCompareAxes, 'on');
                legend(app.MethodCompareAxes, 'Location', 'best');
                title(app.MethodCompareAxes, 'Euler vs RK4 Speed Response');
                xlabel(app.MethodCompareAxes, 'Time (s)');
                ylabel(app.MethodCompareAxes, 'Motor Speed (rad/s)');
                app.MethodCompareAxes.XLim = [0, p.t_end];
                app.TabGroup.SelectedTab = app.PlotsTab;
                app.showPlotView('Numerical Analysis');

                app.CompareStatusLabel.Text = 'Status: Ready';
                app.CompareStatusLabel.FontColor = 'green';

            catch ME
                app.CompareStatusLabel.Text = 'Status: Ready';
                app.CompareStatusLabel.FontColor = 'green';
                uialert(app.UIFigure, ['Compare error: ', ME.message], 'Compare Error', 'Icon', 'error');
