        % Button pushed function: TimeStepStudyButton
        function TimeStepStudyButtonPushed(app, event)
            if app.IsRunning
                return;
            end
            app.IsRunning = true;
            cleanupObj = onCleanup(@() app.setRunningFalse());
            app.TimeStepStatusLabel.Text = 'Status: Simulating...';
            app.TimeStepStatusLabel.FontColor = 'red';
            drawnow;
            try
                if app.SimulationDurationEditField.Value <= 0 || app.TimeStepEditField.Value <= 0
                    uialert(app.UIFigure, 'Simulation Duration and Time Step must be greater than zero.', 'Invalid Input');
                    app.TimeStepStatusLabel.Text = 'Status: Ready';
                    app.TimeStepStatusLabel.FontColor = 'green';
                    return;
                end
                p = app.getSimParams();
                [Va_func, success] = app.getVoltageFunction(p.V_mag, p.t_end);
                if ~success
                    app.TimeStepStatusLabel.Text = 'Status: Ready';
                    app.TimeStepStatusLabel.FontColor = 'green';
                    return;
                end
                TL_func = app.getTorqueFunction(p);
                % ode45 is used ONLY as a validation/reference solution.
                % Tight tolerances so the reference error stays well below RK4's
                % error, and deval (ode45's own continuous interpolant) instead of
                % linear interpolation between ode45 output points.
                ode_fun = @(t,x) DCMotorSimulator.motorDerivative(p, Va_func(t), TL_func, t, x);
                options = odeset('RelTol', 1e-10, 'AbsTol', 1e-10);
                ref_sol = ode45(ode_fun, [0 p.t_end], [p.ia0; p.w0; p.th0; p.Tamb], options);
                % A run is unstable / physically unreasonable if it is non-finite
                % or the speed exceeds a sanity bound.
                isUnstable = @(x) any(~isfinite(x(:))) || max(abs(x(2,:))) > 1e6;
                % ---- Numerical error vs time (RK4 at the user's h) ----
                t_curr = DCMotorSimulator.makeTimeVector(p.t_end, p.h);
                x_curr = DCMotorSimulator.runRK4FixedStep(p, Va_func, TL_func, t_curr);
                x_ref_curr    = deval(ref_sol, t_curr);
                error_vs_time = abs(x_curr(2,:) - x_ref_curr(2,:));
                cla(app.ErrorVsTimeAxes);
                if isUnstable(x_curr)
                    error_vs_time(:) = NaN;
                    grid(app.ErrorVsTimeAxes, 'on');
                    title(app.ErrorVsTimeAxes, {'Numerical Error vs Time (RK4)', sprintf('RK4 is unstable at h = %g s - reduce the time step', p.h)});
                else
                    plot(app.ErrorVsTimeAxes, t_curr, error_vs_time, 'LineWidth', 1.5);
                    grid(app.ErrorVsTimeAxes, 'on');
                    title(app.ErrorVsTimeAxes, 'Numerical Error vs Time (RK4)');
                end
                xlabel(app.ErrorVsTimeAxes, 'Time (s)');
                ylabel(app.ErrorVsTimeAxes, 'Absolute Speed Error (rad/s)');
                app.ErrorVsTimeAxes.XLim = [0 p.t_end];
                max_err = max(error_vs_time, [], 'omitnan');
                if isempty(max_err) || ~isfinite(max_err) || max_err <= 0
                    app.ErrorVsTimeAxes.YLim = [0 1e-6];
                else
                    app.ErrorVsTimeAxes.YLim = [0 1.1*max_err];
                end
                % ---- Max error vs step size ----
                h_array = unique(sort([0.1 0.05 0.01 0.005 0.001 p.h]));
                h_array = h_array(h_array > 0 & h_array < p.t_end);
                if isempty(h_array)
                    h_array = p.h;
                end
                max_error_euler = nan(size(h_array));
                max_error_rk4   = nan(size(h_array));
                for k = 1:numel(h_array)
                    h_test = h_array(k);
                    t_test = DCMotorSimulator.makeTimeVector(p.t_end, h_test);

                    x_e = DCMotorSimulator.runEulerFixedStep(p, Va_func, TL_func, t_test);
                    x_r = DCMotorSimulator.runRK4FixedStep(p, Va_func, TL_func, t_test);

                    x_ref_test = deval(ref_sol, t_test);
                    w_ref_test = x_ref_test(2,:);

                    % Diverged runs are left as NaN (gap in the plot) instead of
                    % astronomically large values that swamp the log axis.
                    if ~isUnstable(x_e)
                        max_error_euler(k) = max(abs(x_e(2,:) - w_ref_test));
                    end
                    if ~isUnstable(x_r)
                        max_error_rk4(k) = max(abs(x_r(2,:) - w_ref_test));
                    end
                end
                unstableE = h_array(isnan(max_error_euler));
                unstableR = h_array(isnan(max_error_rk4));
                cla(app.ErrorVsStepSizeAxes);
                loglog(app.ErrorVsStepSizeAxes, h_array, max_error_euler, '-o', 'LineWidth', 1.5, 'DisplayName', 'Euler Error');
                hold(app.ErrorVsStepSizeAxes, 'on');
                loglog(app.ErrorVsStepSizeAxes, h_array, max_error_rk4, '-s', 'LineWidth', 1.5, 'DisplayName', 'RK4 Error');
                hold(app.ErrorVsStepSizeAxes, 'off');
                grid(app.ErrorVsStepSizeAxes, 'on');
                legend(app.ErrorVsStepSizeAxes, 'Location', 'best');
                ttl = {'Maximum Speed Error vs Time-Step Size'};
                if ~isempty(unstableE) || ~isempty(unstableR)
                    hList = {'none', 'none'};
                    if ~isempty(unstableE), hList{1} = strjoin(arrayfun(@(v) sprintf('%g', v), unstableE, 'UniformOutput', false), ', '); end
                    if ~isempty(unstableR), hList{2} = strjoin(arrayfun(@(v) sprintf('%g', v), unstableR, 'UniformOutput', false), ', '); end
                    ttl{end+1} = sprintf('Unstable (omitted): Euler h = %s | RK4 h = %s', hList{1}, hList{2});
                end
                title(app.ErrorVsStepSizeAxes, ttl);
                xlabel(app.ErrorVsStepSizeAxes, 'Time Step Size (s)');
                ylabel(app.ErrorVsStepSizeAxes, 'Maximum Error (rad/s)');
                app.TabGroup.SelectedTab = app.PlotsTab;
                app.showPlotView('Numerical Analysis');
                app.TimeStepStatusLabel.Text = 'Status: Ready';
                app.TimeStepStatusLabel.FontColor = 'green';
            catch ME
                app.TimeStepStatusLabel.Text = 'Status: Ready';
                app.TimeStepStatusLabel.FontColor = 'green';
                uialert(app.UIFigure, ['Time-step study error: ', ME.message], 'Study Error', 'Icon', 'error');
            end
        end

