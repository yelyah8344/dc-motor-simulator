        % Button pushed function: ImportWaveformButton
        function ImportWaveformButtonPushed(app, event)
            [file, path] = uigetfile('*.csv', 'Select Custom Profile CSV');

            if isequal(file, 0)
                return;
            end

            try
                dataTable = readtable(fullfile(path, file));

                requiredNames = {'Time_s', 'Applied_Voltage_V', 'Load_Torque_Nm'};

                if ~all(ismember(requiredNames, dataTable.Properties.VariableNames))
                    error(['CSV must contain columns: Time_s, ', 'Applied_Voltage_V, Load_Torque_Nm']);
