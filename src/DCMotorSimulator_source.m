        % Button pushed function: RunSimulationButton
        function RunSimulationButtonPushed(app, event)
            if app.IsRunning
                return;
            end
            app.IsRunning = true;
            cleanupObj = onCleanup(@() app.setRunningFalse());
            app.RunStatusLabel.Text = 'Status: Simulating...';
            app.RunStatusLabel.FontColor = 'red';
            drawnow;
            try
                if app.SimulationDurationEditField.Value <= 0 || app.TimeStepEditField.Value <= 0
                    uialert(app.UIFigure, 'Simulation Duration and Time Step must be greater than zero.', 'Invalid Input');
                    app.RunStatusLabel.Text = 'Status: Ready';
                    app.RunStatusLabel.FontColor = 'green';
                    return;
                end
                p = app.getSimParams();
                if p.Ra <= 0 || p.La <= 0 || p.Kt < 0 || p.Ke < 0 || p.J <= 0 || p.B < 0 || p.ILimit <= 0
                    uialert(app.UIFigure, 'Check motor parameters. R, L, J and current limit must be positive; friction/constants cannot be negative.', 'Invalid Motor Parameters');
                    app.RunStatusLabel.Text = 'Status: Ready';
                    app.RunStatusLabel.FontColor = 'green';
                    return;
                end
                [Va_func, success] = app.getVoltageFunction(p.V_mag, p.t_end);
                if ~success
                    app.RunStatusLabel.Text = 'Status: Ready';
                    app.RunStatusLabel.FontColor = 'green';
                    return;
                end
                TL_func = app.getTorqueFunction(p);
                method  = app.NumericalMethodDropDown.Value;
                simData = DCMotorSimulator.simulateDCMotor(p, Va_func, TL_func, method);
                if simData.unstable
                    uialert(app.UIFigure, 'Numerical instability detected. Reduce the time step or check the model parameters.', 'Simulation Failed', 'Icon', 'error');
                    app.RunStatusLabel.Text = 'Status: Ready';
                    app.RunStatusLabel.FontColor = 'green';
                    return;
                end
                app.updatePlots(p, simData);
                app.RunStatusLabel.Text = 'Status: Playing...';
                app.RunStatusLabel.FontColor = 'green';
                drawnow;
                app.setupAndRunAnimation(p, simData);
                app.RunStatusLabel.Text = 'Status: Ready';
                app.RunStatusLabel.FontColor = 'green';
            catch ME
                app.RunStatusLabel.Text = 'Status: Ready';
                app.RunStatusLabel.FontColor = 'green';
                uialert(app.UIFigure, ['Simulation error: ', ME.message], 'Simulation Error', 'Icon', 'error');
            end
        end

