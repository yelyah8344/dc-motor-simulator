                    error('Time_s must contain strictly increasing, unique values.');
                end

                app.ImportedTime = t_imp;
                app.ImportedVoltage = v_imp;
                app.ImportedLoad = tl_imp;

                % Select the imported profile and apply test case M4
                % (Motor A, duration = profile length, h = 1 ms).
                app.applyTestCase('M4');

                uialert(app.UIFigure, sprintf('Voltage and load profile loaded (%.3g s). Test case M4 settings applied: Motor A, h = %g s.', ...
                    app.SimulationDurationEditField.Value, app.TimeStepEditField.Value), 'Import Success', 'Icon', 'success');

            catch ME
                uialert(app.UIFigure, ['Failed to read waveform file: ', ME.message], 'Import Error', 'Icon', 'error');
            end
        end

        % Button pushed function: ImportMeasuredDataButton
        function ImportMeasuredDataButtonPushed(app, event)
            [file, path] = uigetfile({'*.csv;*.txt', 'Data Files (*.csv, *.txt)'}, 'Select Measured Motor Data (Time, Current, Speed)');

            if isequal(file, 0)
                return;
            end

            try
                data = readmatrix(fullfile(path, file));

                if size(data,2) < 3
                    error('The file must contain at least three numeric columns.');
                end

                data = data(:,1:3);

                finiteRows = all(isfinite(data), 2);
                data = data(finiteRows,:);

                if size(data,1) < 2
                    error('Not enough valid measured-data rows.');
                end

                [t_meas, order] = sort(data(:,1));

                if any(diff(t_meas) <= 0)
                    error('Measured time values must be strictly increasing.');
                end

                i_meas = data(order,2);
                w_meas = data(order,3);

                % Sanity check: catch the common mistake of importing the
                % voltage/load-torque waveform file (meant for Import Waveform)
                % into this button by mistake. A genuine (current, speed)
                % recording from THIS motor should have a current comparable to
                % the current limit and a speed comparable to V/Ke, and should
                % not sit implausibly flat for the whole record.
                i_limit  = app.MaxCurrentAEditField.Value;
                v_mag    = app.SupplyVoltageMagnitudeEditField.Value;
                ke       = app.BackEMFConstantEditField.Value;
                w_noload = max(abs(v_mag) / max(abs(ke), eps), 1);

                warnings = {};
                if max(abs(i_meas)) > 3 * max(i_limit, eps)
                    warnings{end+1} = sprintf(['column 2 ("current") reaches %.3g, which is more than 3x ' ...
                        'the current limit of %.3g A - check this is current in amps, not applied voltage.'], ...
                        max(abs(i_meas)), i_limit);
                end
                if max(abs(w_meas)) < 0.02 * w_noload
                    warnings{end+1} = sprintf(['column 3 ("speed") never exceeds %.3g rad/s, which is under 2%% of ' ...
                        'the no-load speed V/Ke = %.3g rad/s - check this is speed in rad/s, not load torque.'], ...
                        max(abs(w_meas)), w_noload);
                end

                if ~isempty(warnings)
                    msg = ['This file does not look like a (time, current, speed) recording from this motor:' newline newline ...
                        strjoin(warnings, [newline newline]) newline newline ...
                        'If this is really the voltage/load-torque profile, use Import Waveform instead. ' ...
                        'Import anyway?'];
                    choice = uiconfirm(app.UIFigure, msg, 'Check Measured Data', ...
                        'Options', {'Import Anyway', 'Cancel'}, 'DefaultOption', 2, 'Icon', 'warning');
                    if ~strcmp(choice, 'Import Anyway')
                        return;
                    end
                end

                app.ImportedMeasuredTime = t_meas;
                app.ImportedMeasuredCurrent = i_meas;
                app.ImportedMeasuredSpeed = w_meas;

                uialert(app.UIFigure, ['Successfully imported measured data from ', file], 'Import Success', 'Icon', 'success');

            catch ME
                uialert(app.UIFigure, ['Failed to read measured data: ', ME.message], 'Import Error', 'Icon', 'error');
            end
        end

