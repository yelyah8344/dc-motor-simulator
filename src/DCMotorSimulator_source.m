        function simData = simulateDCMotor(p, Va_func, TL_func, method)
            % Integrate the motor equations over the requested time span.
            % Inputs : p        - struct of motor and simulation parameters
            %          Va_func  - function handle, applied voltage      Va(t)
            %          TL_func  - function handle, load torque          TL(t, omega)
            %          method   - 'Euler' | 'RK4' | 'RK45 (Adaptive)' | 'Both'
            % Output : simData  - struct with t, ia, w, theta, Te, eb, Va, TL, MotorTemp
            %                     and (for 'Both') the separate Euler and RK4 traces.
            % The solvers only ever see motorDerivative(), so every method integrates
            % exactly the same model.
            % Build a time vector that ALWAYS ends exactly at t_end.
            t = DCMotorSimulator.makeTimeVector(p.t_end, p.h);
            N = numel(t);
            x0 = [p.ia0; p.w0; p.th0; p.Tamb];

            runEuler = strcmp(method,'Euler') || strcmp(method,'Both');
            runRK4   = strcmp(method,'RK4')   || strcmp(method,'Both');

            simData = struct();
            simData.t = t;
            simData.method = method;
            simData.unstable = false;

            % ---------------- Forward Euler ----------------
            if runEuler
                x_euler = zeros(4,N);
                x_euler(:,1) = x0;
                for n = 1:N-1
                    h_n = t(n+1) - t(n);
                    tn  = t(n);
                    dx  = DCMotorSimulator.motorDerivative(p, Va_func(tn), TL_func, tn, x_euler(:,n));
                    x_euler(:,n+1) = x_euler(:,n) + h_n*dx;
                    if any(~isfinite(x_euler(:,n+1)))
                        simData.unstable = true;
                        break;
                    end
                end
                simData.euler_x     = x_euler;
                simData.euler_ia    = x_euler(1,:);
                simData.euler_w     = x_euler(2,:);
                simData.euler_theta = x_euler(3,:);
                simData.euler_T     = x_euler(4,:);
            end

            % ---------------- Classical RK4 ----------------
            % Run RK4 even if Euler diverged, so 'Both' still has data.
            if runRK4
                x_rk4 = zeros(4,N);
                x_rk4(:,1) = x0;
                for n = 1:N-1
                    h_n = t(n+1) - t(n);
                    tn  = t(n);
                    tm  = tn + h_n/2;
                    tn1 = t(n+1);

                    k1 = DCMotorSimulator.motorDerivative(p, Va_func(tn),  TL_func, tn,  x_rk4(:,n));
                    k2 = DCMotorSimulator.motorDerivative(p, Va_func(tm),  TL_func, tm,  x_rk4(:,n) + (h_n/2)*k1);
                    k3 = DCMotorSimulator.motorDerivative(p, Va_func(tm),  TL_func, tm,  x_rk4(:,n) + (h_n/2)*k2);
                    % k4 is the slope at the END of [tn, tn1): evaluate the inputs
                    % just inside the interval (left limit) so a step in Va or TL
                    % at tn1 does not leak into this step (keeps RK4 4th order).
                    tn1_in = tn1 - 1e-9*h_n;
                    k4 = DCMotorSimulator.motorDerivative(p, Va_func(tn1_in), TL_func, tn1_in, x_rk4(:,n) + h_n*k3);

                    x_rk4(:,n+1) = x_rk4(:,n) + (h_n/6)*(k1 + 2*k2 + 2*k3 + k4);

                    if any(~isfinite(x_rk4(:,n+1)))
                        simData.unstable = true;
                        break;
                    end
                end
                simData.rk4_x     = x_rk4;
                simData.rk4_ia    = x_rk4(1,:);
                simData.rk4_w     = x_rk4(2,:);
                simData.rk4_theta = x_rk4(3,:);
                simData.rk4_T     = x_rk4(4,:);
            end

            % ---------------- Adaptive RK45 ----------------
            if strcmp(method,'RK45 (Adaptive)')
                [t45, x45, rk45_ok] = DCMotorSimulator.runAdaptiveRK45(p, Va_func, TL_func, x0);
                simData.t = t45;
                simData.rk45_x     = x45;
                simData.rk45_ia    = x45(1,:);
                simData.rk45_w     = x45(2,:);
                simData.rk45_theta = x45(3,:);
                simData.rk45_T     = x45(4,:);
                if ~rk45_ok
                    simData.unstable = true;
                end
            end

            % ---------------- Pick the primary result ----------------
            x_primary = [];
            switch method
                case 'Euler'
                    if isfield(simData,'euler_x'), x_primary = simData.euler_x; end
                case {'RK4','Both'}
                    if isfield(simData,'rk4_x'),   x_primary = simData.rk4_x;   end
                case 'RK45 (Adaptive)'
                    if isfield(simData,'rk45_x'),  x_primary = simData.rk45_x;  end
            end

            % If nothing usable exists, flag as unstable and return early so
            % the GUI can show its alert instead of crashing on a missing field.
            if isempty(x_primary)
                simData.unstable = true;
                simData.ia = []; simData.w = []; simData.theta = []; simData.MotorTemp = [];
                simData.Va = []; simData.TL = []; simData.Te = []; simData.eb = [];
                return;
            end

            simData.ia        = x_primary(1,:);
            simData.w         = x_primary(2,:);
            simData.theta     = x_primary(3,:);
            simData.MotorTemp = x_primary(4,:);

            % The waveform handles are vectorised, so call them directly.
            % Applied voltage as seen by the motor: include the current limiter,
            % using the same effective resistance as motorDerivative.
            Va_cmd = Va_func(simData.t);
            if p.useLimit
                if p.useThermal
                    Ra_eff = max(p.Ra*(1 + p.alpha*(simData.MotorTemp - p.Tamb)), 0.01*p.Ra);
                else
                    Ra_eff = p.Ra;
                end
                Va_cmd = min(max(Va_cmd, -Ra_eff.*p.ILimit + p.Ke.*simData.w), Ra_eff.*p.ILimit + p.Ke.*simData.w);
            end
            simData.Va = Va_cmd;
            simData.TL = TL_func(simData.t, simData.w);
            simData.TL_func = TL_func;   % used to draw the load characteristic
            simData.Te = p.Kt .* simData.ia;
            simData.eb = p.Ke .* simData.w;

            % Compatibility aliases so updatePlots can read either naming style.
            if isfield(simData,'euler_ia')
                simData.ia_euler = simData.euler_ia;
                simData.w_euler  = simData.euler_w;
            end

            % Final physical sanity checks (primary AND Euler in 'Both' mode).
            if any(~isfinite(x_primary(:))) || any(abs(simData.w) > 1e6) || any(abs(simData.ia) > 1e9)
                simData.unstable = true;
            end
            if isfield(simData,'euler_x')
                if any(~isfinite(simData.euler_x(:))) || any(abs(simData.euler_w) > 1e6)
                    simData.unstable = true;
                end
            end
        end

        function [t_out, y_out, ok] = validateImportedWaveform(t_in, y_in)
            % Check a waveform read from a CSV before it is used.
            % Rejects empty data, mismatched column lengths, non-finite values and
            % time vectors that are not strictly increasing (interp1 needs that).
            ok = false;
            t_out = [];
            y_out = [];
            if isempty(t_in) || isempty(y_in)
                return;
            end
            t_in = t_in(:);
            y_in = y_in(:);
            if numel(t_in) ~= numel(y_in) || numel(t_in) < 2
                return;
            end
            finiteRows = isfinite(t_in) & isfinite(y_in);
            t_in = t_in(finiteRows);
            y_in = y_in(finiteRows);
            if numel(t_in) < 2
                return;
            end
            [t_out, order] = sort(t_in);
            y_out = y_in(order);
            if any(diff(t_out) <= 0)
                ok = false;
                return;
            end
            ok = true;
        end

        function dx = motorDerivative(p, Va_unlimited, TL_func, t, x)
            % THE MODEL. Return dx/dt for the present state x.
            % x = [ia; omega; theta; T_winding].  Called by every solver, at every
            % stage, so all the physics lives here and nowhere else:
            %   - optional thermal model  : winding temperature changes Ra
            %   - optional current limit  : clamps Va around the back-EMF
            %   - optional Coulomb friction
            %   - the four state equations themselves
            % TL_func(t, w): load torque as a function of time AND speed
            % (speed-dependent load characteristics, switched on at t_load).
            ia = x(1);
            w  = x(2);
            TL = TL_func(t, w);

            if numel(x) >= 4
                T = x(4);
            else
                T = p.Tamb;
            end

            % Temperature-dependent armature resistance.
            if p.useThermal
                Ra_eff = p.Ra * (1 + p.alpha*(T - p.Tamb));
                Ra_eff = max(Ra_eff, 0.01*p.Ra);   % keep it physical
            else
                Ra_eff = p.Ra;
            end

            % Current limiter: clamp the applied voltage around the back-EMF
            % using the SAME effective resistance as the electrical model.
            if p.useLimit
                Vmax = Ra_eff*p.ILimit + p.Ke*w;
                Vmin = -Ra_eff*p.ILimit + p.Ke*w;
                Va = min(max(Va_unlimited, Vmin), Vmax);
            else
                Va = Va_unlimited;
            end

            % Optional Coulomb friction (smoothed sign).
            if p.EnableCoulomb
                T_coulomb = p.Tc*tanh(w/0.01);
            else
                T_coulomb = 0;
            end

            dia    = (Va - Ra_eff*ia - p.Ke*w) / p.La;                 % Va = La*dia/dt + Ra*ia + Ke*w
            dw     = (p.Kt*ia - p.B*w - TL - T_coulomb) / p.J;         % J*dw/dt = Kt*ia - B*w - TL - Tf
            dtheta = w;

            if p.useThermal
                dT = (ia^2*Ra_eff - (T - p.Tamb)/p.Rth) / p.Cth;
            else
                dT = 0;
            end

            dx = [dia; dw; dtheta; dT];
        end

        function [t_out, x_out, ok] = runAdaptiveRK45(p, Va_func, TL_func, x0)
            % Adaptive-step Runge-Kutta-Fehlberg 4(5) solver.
            % Six slope evaluations give both a 4th- and a 5th-order estimate of the
            % step; their difference estimates the local error. If the error is too
            % large the step is rejected and retried smaller, otherwise it is accepted
            % and the step grows. Returns ok = false if it cannot converge.
            t = 0;
            x = x0;

            h = min(p.h, p.t_end/100);
            h = max(h, p.t_end/1e6);

            h_min = max(p.t_end*1e-10, eps);
            % Cap the step so a 50 Hz waveform cannot be stepped over.
            h_max = min(max(10*p.h, 1e-4), 0.02);

            maxAcceptedSteps = 5e6;
            maxRejectedSteps = 1000;
            accepted = 0;
            rejected = 0;

            t_out = zeros(1, 1000);
            x_out = zeros(4, 1000);
            t_out(1)   = t;
            x_out(:,1) = x;
            outIndex = 1;
            ok = true;

            while t < p.t_end
                if accepted >= maxAcceptedSteps
                    ok = false;
                    break;
                end

                h = min(h, p.t_end - t);

                % Fehlberg embedded 4(5) pair.
                k1 = DCMotorSimulator.motorDerivative(p, Va_func(t),          TL_func, t,          x);
                k2 = DCMotorSimulator.motorDerivative(p, Va_func(t+h/4),      TL_func, t+h/4,      x + h*(k1/4));
                k3 = DCMotorSimulator.motorDerivative(p, Va_func(t+3*h/8),    TL_func, t+3*h/8,    x + h*(3*k1/32 + 9*k2/32));
                k4 = DCMotorSimulator.motorDerivative(p, Va_func(t+12*h/13),  TL_func, t+12*h/13,  x + h*(1932*k1/2197 - 7200*k2/2197 + 7296*k3/2197));
                t_end_in = t + h - 1e-9*h;   % left limit at the end of the step
                k5 = DCMotorSimulator.motorDerivative(p, Va_func(t_end_in),   TL_func, t_end_in,        x + h*(439*k1/216 - 8*k2 + 3680*k3/513 - 845*k4/4104));
                k6 = DCMotorSimulator.motorDerivative(p, Va_func(t+h/2),      TL_func, t+h/2,      x + h*(-8*k1/27 + 2*k2 - 3544*k3/2565 + 1859*k4/4104 - 11*k5/40));

                x4 = x + h*(25*k1/216 + 1408*k3/2565 + 2197*k4/4104 - k5/5);
                x5 = x + h*(16*k1/135 + 6656*k3/12825 + 28561*k4/56430 - 9*k5/50 + 2*k6/55);

                % Per-component scaling: current, speed, angle and temperature
                % have different units/magnitudes, so each gets its own tolerance.
                scale   = p.AbsTol + p.RelTol*max(abs(x), abs(x5));
                errNorm = max(abs(x5 - x4) ./ max(scale, eps));

                if ~isfinite(errNorm)
                    ok = false;
                    break;
                end

                if errNorm <= 1
                    % ---- accepted step ----
                    t = t + h;
                    x = x5;
                    accepted = accepted + 1;
                    rejected = 0;

                    outIndex = outIndex + 1;
                    if outIndex > size(t_out,2)
                        newSize = size(t_out,2)*2;
                        t_out(1, end+1:newSize)   = 0;
                        x_out(:, end+1:newSize)   = 0;
                    end
                    t_out(outIndex)   = t;
                    x_out(:,outIndex) = x;

                    if errNorm == 0
                        factor = 2.0;
                    else
                        factor = min(2.0, max(0.2, 0.9*(1/errNorm)^(1/5)));
                    end
                    h = min(h_max, max(h_min, h*factor));
                else
                    % ---- rejected step ----
                    rejected = rejected + 1;
                    if rejected > maxRejectedSteps
                        ok = false;
                        break;
                    end
                    factor = min(0.5, max(0.1, 0.9*(1/max(errNorm,eps))^(1/5)));
                    if h <= h_min*(1 + 1e-12)
                        ok = false;
                        break;
                    end
                    h = max(h_min, h*factor);
                end

                if any(~isfinite(x)) || abs(x(1)) > 1e9 || abs(x(2)) > 1e9
                    ok = false;
                    break;
                end
            end

            t_out = t_out(1:outIndex);
            x_out = x_out(:,1:outIndex);
            if isempty(t_out)
                ok = false;
            end
        end

        function t = makeTimeVector(t_end, h)
            % Build a uniform time grid 0 : h : t_end.
            % The final point is forced to land exactly on t_end, so the last step may
            % be slightly shorter than h.
            if t_end <= 0 || h <= 0
                error('Simulation duration and time step must be positive.');
            end
            n = floor(t_end/h);
            t = (0:n)*h;
            if isempty(t) || abs(t(end) - t_end) > 100*eps(max(1,t_end))
                t = [t, t_end];      % add a shorter final step
            else
                t(end) = t_end;
            end
            t = unique(t, 'stable');
        end

        function x = runEulerFixedStep(p, Va_func, TL_func, t)
            % Forward Euler: x(n+1) = x(n) + h * f(t(n), x(n)).
            % One derivative evaluation per step. Global error is O(h) - first order.
            N = numel(t);
            x = zeros(4,N);
            x(:,1) = [p.ia0; p.w0; p.th0; p.Tamb];
            for n = 1:N-1
                h  = t(n+1) - t(n);
                dx = DCMotorSimulator.motorDerivative(p, Va_func(t(n)), TL_func, t(n), x(:,n));
                x(:,n+1) = x(:,n) + h*dx;
                if any(~isfinite(x(:,n+1)))
                    x(:,n+2:end) = NaN;     % mark the rest as invalid
                    break;
                end
            end
        end

        function x = runRK4FixedStep(p, Va_func, TL_func, t)
            % Classical fourth-order Runge-Kutta.
            % Four derivative evaluations per step, combined with weights 1:2:2:1.
            % Global error is O(h^4), so halving h cuts the error by about 16 times.
            N = numel(t);
            x = zeros(4,N);
            x(:,1) = [p.ia0; p.w0; p.th0; p.Tamb];
            for n = 1:N-1
                h   = t(n+1) - t(n);
                tn  = t(n);
                tm  = tn + h/2;
                tn1 = t(n+1);

                k1 = DCMotorSimulator.motorDerivative(p, Va_func(tn),  TL_func, tn,  x(:,n));
                k2 = DCMotorSimulator.motorDerivative(p, Va_func(tm),  TL_func, tm,  x(:,n) + (h/2)*k1);
                k3 = DCMotorSimulator.motorDerivative(p, Va_func(tm),  TL_func, tm,  x(:,n) + (h/2)*k2);
                tn1_in = tn1 - 1e-9*h;   % left limit (see simulateDCMotor)
                k4 = DCMotorSimulator.motorDerivative(p, Va_func(tn1_in), TL_func, tn1_in, x(:,n) + h*k3);

                x(:,n+1) = x(:,n) + (h/6)*(k1 + 2*k2 + 2*k3 + k4);
                if any(~isfinite(x(:,n+1)))
                    x(:,n+2:end) = NaN;
                    break;
                end
            end
        end
    end


