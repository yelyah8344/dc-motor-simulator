        function TL_func = getTorqueFunction(app, p)
            % Build the load-torque handle TL(t, omega).
            % TL = u(t - t_load) * g(omega): the load is switched on at the Load
            % Application Time, and from then on follows its own torque-speed
            % characteristic g. A real load's torque depends on how fast it is driven,
            % which is why omega is an argument and not just t.
            % Load torque TL(t, w) = u(t - t_load) * f(w): the load is switched
            % on at the Load Application Time, and its size then follows the
            % load's torque-speed characteristic f(w).
            % "Load-Torque Magnitude" is the torque at the reference speed
            % w_ref = V/Ke (the motor's no-load speed at the supply voltage).
            w_ref = max(abs(p.V_mag) / max(p.Ke, eps), eps);
            Tm    = p.TL_mag;
            tOn   = p.TL_time;
            on    = @(t) double(t >= tOn);
            dirn  = @(w) tanh(w ./ (1e-3*w_ref));   % smooth sign: passive loads oppose rotation

            profile = app.LoadTorqueProfileDropDown.Value;
            switch profile
                case 'Constant (T = K)'
                    % hoists, cranes, conveyors: same torque at every speed
                    TL_func = @(t, w) on(t) .* Tm .* ones(size(w));

                case 'Linear (T ∝ ω)'
                    % generator / eddy-current brake: T = K*w
                    TL_func = @(t, w) on(t) .* Tm .* (w ./ w_ref);

                case 'Quadratic (T ∝ ω²)'
                    % fans, blowers, centrifugal pumps: T = K*w^2 (opposing rotation)
                    TL_func = @(t, w) on(t) .* Tm .* (w .* abs(w)) ./ w_ref^2;

                case 'Constant Power (T ∝ 1/ω)'
                    % winders: T = P/w with P = Tm*w_ref; limited to 10*Tm
                    % below 10 % of w_ref so it stays finite at standstill
                    TL_func = @(t, w) on(t) .* Tm .* min(w_ref ./ max(abs(w), eps), 10) .* dirn(w);

                case 'Imported File'
                    if isempty(app.ImportedTime) || isempty(app.ImportedLoad)
                        TL_func = @(t, w) zeros(size(t));
                        return;
                    end
                    [t_load, load_imp, ok_l] = DCMotorSimulator.validateImportedWaveform(app.ImportedTime, app.ImportedLoad);
                    if ~ok_l
                        TL_func = @(t, w) zeros(size(t));
                        return;
                    end
                    % measured load profile: a function of time only
                    TL_func = @(t, w) interp1(t_load, load_imp, t, 'linear', 'extrap');

                otherwise
                    TL_func = @(t, w) zeros(size(t));
            end
        end

        function [Va_func, success] = getVoltageFunction(app, V_mag, ~)
            % Build the applied-voltage handle Va(t) for the selected waveform.
            % Returns success = false (and a zero waveform) if the inputs are invalid,
            % so the caller can abort cleanly.
            success = true;
            waveform_type = app.VoltageWaveformDropDown.Value;

            switch waveform_type
                case 'Step'
                    Va_func = @(t) V_mag .* ones(size(t));

                case 'Ramp'
                    % Rise from 0 to V_mag over RampDuration, then hold V_mag.
                    Tr = app.RampDuration;
                    if Tr > 0
                        Va_func = @(t) V_mag .* min(max(t ./ Tr, 0), 1);
                    else
                        Va_func = @(t) V_mag .* ones(size(t));   % zero ramp time = step
                    end

                case 'Pulse'
                    % V_mag between PulseStartTime and PulseEndTime, 0 otherwise.
                    ts = app.PulseStartTime;
                    te = app.PulseEndTime;
                    if te <= ts
                        uialert(app.UIFigure, 'Pulse end time must be greater than pulse start time.', 'Invalid Input');
                        success = false;
                        Va_func = @(t) zeros(size(t));
                        return;
                    end
                    Va_func = @(t) V_mag .* (t >= ts & t < te);

                case 'Imported File'
                    if isempty(app.ImportedTime) || isempty(app.ImportedVoltage)
                        uialert(app.UIFigure, 'No imported voltage waveform is loaded. Import a CSV first.', 'Missing Data');
                        success = false;
                        Va_func = @(t) zeros(size(t));
                        return;
                    end
                    [t_imp, v_imp, ok] = DCMotorSimulator.validateImportedWaveform(app.ImportedTime, app.ImportedVoltage);
                    if ~ok
                        uialert(app.UIFigure, 'Imported waveform contains invalid or insufficient data.', 'Invalid Imported Waveform');
                        success = false;
                        Va_func = @(t) zeros(size(t));
                        return;
                    end
                    Va_func = @(t) interp1(t_imp, v_imp, min(max(t,t_imp(1)),t_imp(end)), 'linear');

                case 'User-defined'
                    waveChoice = questdlg('Select Waveform Type:', 'Custom Waveform', 'PULSE', 'SINE', 'PULSE');
                    if isempty(waveChoice)
                        success = false;
                        Va_func = @(t) zeros(size(t));
                        return;
                    end

                    if strcmp(waveChoice, 'PULSE')
                        prompt = {'Initial Voltage (V1):', 'Peak Voltage (V2):', 'Delay Time (s):', 'Rise Time (s):', 'Fall Time (s):', 'Pulse Width (s):', 'Period (s):'};
                        definput = {'0', num2str(V_mag), '1', '0.1', '0.1', '2', '5'};
                        ans_cell = inputdlg(prompt, 'PULSE Parameters', [1 50], definput);
                        if isempty(ans_cell)
                            success = false;
                            Va_func = @(t) zeros(size(t));
                            return;
                        end
                        v1  = app.parseValue(ans_cell{1});
                        v2  = app.parseValue(ans_cell{2});
                        td  = app.parseValue(ans_cell{3});
                        tr  = max(app.parseValue(ans_cell{4}), 1e-9);
                        tf  = max(app.parseValue(ans_cell{5}), 1e-9);
                        pw  = max(app.parseValue(ans_cell{6}), 0);
                        per = app.parseValue(ans_cell{7});

                        if per <= 0
                            uialert(app.UIFigure, 'Period must be greater than zero.', 'Invalid Input');
                            success = false;
                            Va_func = @(t) zeros(size(t));
                            return;
                        end
                        pulse_val = @(tm) (tm < td) .* v1 ...
                            + (tm >= td & tm < td+tr) .* (v1 + (v2-v1).*(tm-td)./tr) ...
                            + (tm >= td+tr & tm < td+tr+pw) .* v2 ...
                            + (tm >= td+tr+pw & tm < td+tr+pw+tf) .* (v2 - (v2-v1).*(tm-(td+tr+pw))./tf) ...
                            + (tm >= td+tr+pw+tf) .* v1;
                        Va_func = @(t) pulse_val(mod(t, per));

                    elseif strcmp(waveChoice, 'SINE')
                        % Default: DC supply with 10 % ripple at 100 Hz (full-wave
                        % rectified 50 Hz mains), i.e. a realistic DC-motor input.
                        prompt = {'DC Offset (V):', 'Ripple Amplitude (V):', 'Ripple Frequency (Hz):', 'Delay (s):', 'Damping Factor:'};
                        definput = {num2str(V_mag), num2str(0.1*V_mag), '100', '0', '0'};
                        ans_cell = inputdlg(prompt, 'SINE Parameters', [1 50], definput);
                        if isempty(ans_cell)
                            success = false;
                            Va_func = @(t) zeros(size(t));
                            return;
                        end
                        vo    = app.parseValue(ans_cell{1});
                        va    = app.parseValue(ans_cell{2});
                        freq  = app.parseValue(ans_cell{3});
                        td    = app.parseValue(ans_cell{4});
                        theta = app.parseValue(ans_cell{5});

                        if freq < 0 || theta < 0
                            uialert(app.UIFigure, 'Frequency and damping factor must be nonnegative.', 'Invalid Input');
                            success = false;
                            Va_func = @(t) zeros(size(t));
                            return;
                        end
                        Va_func = @(t) (t < td) .* vo + (t >= td) .* (vo + va .* exp(-theta.*(t-td)) .* sin(2*pi*freq.*(t-td)));
                    else
                        success = false;
                        Va_func = @(t) zeros(size(t));
                    end

                otherwise
                    uialert(app.UIFigure, ['Unsupported voltage waveform: ', waveform_type], 'Invalid Waveform');
                    success = false;
                    Va_func = @(t) zeros(size(t));
            end
        end

