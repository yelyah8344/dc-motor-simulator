        function val = parseValue(~, inputStr)
            % Parse a number typed into a dialog box, accepting '2.5e-3' style
            % input and returning NaN if it is not a valid finite number.
            str = lower(strtrim(inputStr));
            tokens = regexp(str, '^([+-]?\d*\.?\d+(?:e[+-]?\d+)?)([a-z]*)$', 'tokens');
            if isempty(tokens)
                val = str2double(str);
                return;
            end
            numVal = str2double(tokens{1}{1});
            suffix = tokens{1}{2};
            switch suffix
                case 'f',   mult = 1e-15;
                case 'p',   mult = 1e-12;
                case 'n',   mult = 1e-9;
                case 'u',   mult = 1e-6;
                case 'm',   mult = 1e-3;
                case 'k',   mult = 1e3;
                case 'meg', mult = 1e6;
                case 'g',   mult = 1e9;
                case 't',   mult = 1e12;
                otherwise,  mult = 1;
            end
            val = numVal * mult;
        end

        function updatePlots(app, p, simData)
